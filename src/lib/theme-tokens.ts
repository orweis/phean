/**
 * Every theme's token values, light and dark: the single source of truth for Phean's colours.
 * `pnpm themes` writes `src/app/themes.css` from this file, `tests/themes.test.ts` checks that the
 * stylesheet matches it and that every pair a component draws holds its contrast, and `lib/themes.ts`
 * keeps the browser chrome's colour in step with each theme's paper.
 *
 * A theme is a named set of these tokens; components only ever name the token (`bg-panel`,
 * `text-accent-ink`), so a theme changes every screen without touching one of them. Values are
 * `oklch()` literals or a reference to another token (`ref("signal")`), which resolves in the theme
 * that is in force. Plain data, so it is client-safe, but only the server and the tests import it.
 */


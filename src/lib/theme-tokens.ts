/** A token's own colour in one palette, following references to the token they name. */
export function resolveColor(colors: Record<ColorToken, string>, token: ColorToken): string {
  const seen = new Set<ColorToken>();
  let value = colors[token];
  for (let match = /^var\(--color-([a-z0-9-]+)\)$/.exec(value); match; match = /^var\(--color-([a-z0-9-]+)\)$/.exec(value)) {
    const next = match[1] as ColorToken;
    if (seen.has(next)) throw new Error(`A reference loop through ${next}`);
    seen.add(next);
    value = colors[next];
  }
  return value;
}

export type ColorToken = (typeof COLOR_TOKENS)[number];

export const SHADOW_TOKENS = ["float", "raised", "lift", "window", "window-behind"] as const;
export type ShadowToken = (typeof SHADOW_TOKENS)[number];

export interface Palette {
  colors: Record<ColorToken, string>;
  shadows: Record<ShadowToken, string>;
}

export interface ThemeTokens {
  light: Palette;
  dark: Palette;
}

/** A token that takes another's value in whichever theme and appearance is in force. */
export const ref = (token: ColorToken) => `var(--color-${token})`;

/** The tokens every theme derives the same way, so a role means the same in all of them. */
const DERIVED = {
  wait: ref("signal"),
  "wait-tint": ref("signal-tint"),
  move: ref("station-progress"),
  "move-ink": ref("accent-ink"),
  "move-tint": ref("accent-tint"),
  "station-inbox": ref("inbox"),
} as const satisfies Partial<Record<ColorToken, string>>;

type Own = Omit<Record<ColorToken, string>, keyof typeof DERIVED>;

function palette(colors: Own, shadows: Record<ShadowToken, string>): Palette {
  return { colors: { ...colors, ...DERIVED }, shadows };
}

/** Dark as the light palette with the tokens that move: how Ledger was always written. */
function over(light: Palette, colors: Partial<Own>, shadows: Partial<Record<ShadowToken, string>>): Palette {
  return { colors: { ...light.colors, ...colors }, shadows: { ...light.shadows, ...shadows } };
}


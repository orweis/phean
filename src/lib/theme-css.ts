import { COLOR_TOKENS, SHADOW_TOKENS, THEME_TOKENS, type Palette } from "./theme-tokens";
import { DEFAULT_THEME, THEMES, type ThemeId } from "./themes";

/**
 * `src/app/themes.css`, written from the tokens by `pnpm themes`. The `@theme` block declares every
 * token to Tailwind (with the default theme's light values, so the utilities exist); each theme then
 * sets its own values under `[data-theme]`, light by default and dark under the appearance:
 * `<html data-appearance="dark">`, or System (or no choice) on a device that prefers dark. The rules
 * match `[data-theme]` on `<html>` and on any element inside it, so a swatch can show another theme.
 */
export function renderThemeCss(): string {
  const lines = [
    "/* Generated by `pnpm themes` from src/lib/theme-tokens.ts. Edit the tokens there, never this file. */",
    "",
    "@theme {",
    "  --color-*: initial;",
    ...declarations(THEME_TOKENS[DEFAULT_THEME].light),
    "}",
    "",
    "@layer base {",
  ];
  for (const theme of THEMES) {
    const { light, dark } = THEME_TOKENS[theme];
    lines.push(`  /* ${theme} */`, `  [data-theme="${theme}"] {`, "    color-scheme: light;", ...declarations(light, "    "), "  }", "");
    lines.push(`  ${darkSelector(theme, '[data-appearance="dark"]')} {`, "    color-scheme: dark;", ...declarations(dark, "    "), "  }", "");
    lines.push(
      "  @media (prefers-color-scheme: dark) {",
      `    ${darkSelector(theme, ':not([data-appearance="light"])')} {`,
      "      color-scheme: dark;",
      ...declarations(dark, "      "),
      "    }",
      "  }",
      "",
    );
  }
  lines.pop();
  lines.push("}", "");
  return lines.join("\n");
}

function darkSelector(theme: ThemeId, appearance: string): string {
  return `:root${appearance}[data-theme="${theme}"], :root${appearance} [data-theme="${theme}"]`;
}

function declarations({ colors, shadows }: Palette, indent = "  "): string[] {
  return [
    ...COLOR_TOKENS.map((token) => `${indent}--color-${token}: ${colors[token]};`),
    ...SHADOW_TOKENS.map((token) => `${indent}--shadow-${token}: ${shadows[token]};`),
  ];
}

"""Draws the landing page's contour map of the slope: public/landing/slope.svg.

The map is a mask (white lines, alpha only), so the page colours it with its own tokens.
The route the agents climb and its stations are printed as TypeScript for
src/components/landing/slope-route.ts, in the same 1600x900 coordinates.

Run: python3 scripts/art/slope.py  (needs numpy and matplotlib)
"""

import json
import math
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

W, H = 1600, 900
ROOT = Path(__file__).resolve().parents[2]
rng = np.random.default_rng(72450919)

xs = np.linspace(0, W, 640)
ys = np.linspace(0, H, 360)
X, Y = np.meshgrid(xs, ys)


def bump(cx, cy, sx, sy, h, rot=0.0):
    c, s = math.cos(rot), math.sin(rot)
    dx, dy = X - cx, Y - cy
    u, v = c * dx + s * dy, -s * dx + c * dy
    return h * np.exp(-((u / sx) ** 2 + (v / sy) ** 2))


# A slope that rises from the lower left and steepens toward a summit at the upper right, as the logo's hill does.
s = np.clip(X / W * 0.78 + (1 - Y / H) * 0.62, 0, None)
Z = s**2.1
Z += bump(1450, 185, 240, 170, 0.55)  # the summit
Z += bump(1180, 380, 300, 90, 0.16, rot=-0.55)  # a shoulder ridge running down from it
Z += bump(560, 640, 220, 120, 0.09, rot=0.3)  # a knoll on the lower slope
Z -= bump(860, 560, 360, 70, 0.07, rot=-0.75)  # a gully
# Low-frequency ripples, so the lines read as ground and not as a chart.
for _ in range(9):
    fx, fy = rng.uniform(0.6, 2.4, 2) / W * 2 * math.pi
    ph = rng.uniform(0, 2 * math.pi)
    Z += 0.012 * np.sin(fx * X * rng.choice([-1, 1]) + fy * Y + ph)

levels = np.linspace(Z.min() + 0.02, Z.max() - 0.01, 46)
fig = plt.figure()
cs = plt.contour(X, Y, Z, levels=levels)
zmin, zmax = levels[0], levels[-1]


def fmt(v):
    return f"{v:.1f}".rstrip("0").rstrip(".")


paths = []
for i, (level, segs) in enumerate(zip(cs.levels, cs.allsegs)):
    index = i % 5 == 0
    t = (level - zmin) / (zmax - zmin)
    # Lines brighten toward the summit, where the last light is.
    alpha = 0.22 + 0.5 * t**1.3 + (0.18 if index else 0)
    width = 1.6 if index else 0.9
    for seg in segs:
        if len(seg) < 4:
            continue
        pts = seg[::3] if len(seg) > 60 else seg
        d = "M" + "L".join(f"{fmt(x)} {fmt(y)}" for x, y in pts)
        paths.append(f'<path d="{d}" stroke-opacity="{alpha:.2f}" stroke-width="{width}"/>')
plt.close(fig)

svg = (
    f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" preserveAspectRatio="xMaxYMid slice">'
    '<g fill="none" stroke="#fff" stroke-linejoin="round" stroke-linecap="round">'
    + "".join(paths)
    + "</g></svg>\n"
)
out = ROOT / "public/landing/slope.svg"
out.write_text(svg)
print(f"wrote {out} ({len(svg) // 1024} KB, {len(paths)} lines)")

# The route: switchbacks from the foot of the slope to the summit, smoothed with Catmull-Rom.
waypoints = [(780, 890), (900, 805), (1075, 785), (1150, 705), (1015, 645), (1110, 565), (1290, 535), (1345, 455), (1215, 405), (1290, 325), (1395, 268), (1440, 205)]


def catmull(points, steps=24):
    p = [points[0], *points, points[-1]]
    out = []
    for i in range(1, len(p) - 2):
        p0, p1, p2, p3 = map(np.array, (p[i - 1], p[i], p[i + 1], p[i + 2]))
        for k in range(steps):
            t = k / steps
            out.append(0.5 * ((2 * p1) + (-p0 + p2) * t + (2 * p0 - 5 * p1 + 4 * p2 - p3) * t**2 + (-p0 + 3 * p1 - 3 * p2 + p3) * t**3))
    out.append(np.array(points[-1]))
    return np.array(out)


curve = catmull(waypoints)
lengths = np.r_[0, np.cumsum(np.linalg.norm(np.diff(curve, axis=0), axis=1))]


def at(fraction):
    target = fraction * lengths[-1]
    i = int(np.searchsorted(lengths, target))
    i = min(max(i, 1), len(curve) - 1)
    a, b = curve[i - 1], curve[i]
    t = (target - lengths[i - 1]) / max(lengths[i] - lengths[i - 1], 1e-9)
    x, y = a + (b - a) * t
    return round(float(x), 1), round(float(y), 1)


# Bezier form of the same curve for SVG (Catmull-Rom to cubic).
p = [waypoints[0], *waypoints, waypoints[-1]]
d = f"M{waypoints[0][0]} {waypoints[0][1]}"
for i in range(1, len(p) - 2):
    p0, p1, p2, p3 = map(np.array, (p[i - 1], p[i], p[i + 1], p[i + 2]))
    c1 = p1 + (p2 - p0) / 6
    c2 = p2 - (p3 - p1) / 6
    d += f"C{fmt(c1[0])} {fmt(c1[1])} {fmt(c2[0])} {fmt(c2[1])} {fmt(p2[0])} {fmt(p2[1])}"

stations = {name: at(f) for name, f in [("inbox", 0.1), ("todo", 0.3), ("progress", 0.5), ("waiting", 0.7), ("done", 0.88)]}
ts = (
    "// Generated by scripts/art/slope.py; edit the script, not this file.\n"
    "/** The route the agents climb on the landing's contour map, in the map's 1600x900 coordinates. */\n"
    f"export const SLOPE_ROUTE = {json.dumps(d)};\n\n"
    "/** Where each station sits on the route. */\n"
    f"export const SLOPE_STATIONS = {json.dumps(stations)} as const;\n\n"
    "/** The summit, where the route ends. */\n"
    f"export const SLOPE_SUMMIT = {json.dumps(list(waypoints[-1]))} as const;\n"
)
(ROOT / "src/components/landing/slope-route.ts").write_text(ts)
print("wrote src/components/landing/slope-route.ts")

/**
 * Bundles the service worker (`src/lib/service-worker.ts` and the client-safe `src/lib` modules it
 * imports) into one classic script for `public/sw.js`. A service worker cannot import TypeScript, and
 * the root has no bundler of its own, so each module is transpiled to CommonJS with the TypeScript
 * compiler the repository already uses and wrapped, unindented (a template literal may span lines),
 * in a tiny module table. The output depends only on the sources, so `tests/service-worker.test.ts`
 * checks the committed file is in step.
 */
import { readFileSync } from "node:fs";
import path from "node:path";

import ts from "typescript";

const LIB = path.resolve(import.meta.dirname, "../src/lib");
const ENTRY = "service-worker";

const HEADER = `// Generated by \`pnpm sw\` (scripts/service-worker.ts) from src/lib/service-worker.ts and src/lib/push.ts. Do not edit.
// It handles page navigations only, caches nothing but /offline and its static files, and shows Web Push notifications.
`;

/** One module: transpiled to CommonJS, with the relative modules it requires. */
function transpile(name: string): { code: string; requires: string[] } {
  const source = readFileSync(path.join(LIB, `${name}.ts`), "utf8");
  const { outputText } = ts.transpileModule(source, {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022, removeComments: true, esModuleInterop: false, verbatimModuleSyntax: false },
    fileName: `${name}.ts`,
  });
  const requires: string[] = [];
  for (const match of outputText.matchAll(/require\("([^"]+)"\)/g)) {
    const specifier = match[1]!;
    if (!specifier.startsWith("./") || specifier.slice(2).includes("/")) {
      throw new Error(`${name}.ts imports ${specifier}: the service worker may import only sibling modules of src/lib`);
    }
    requires.push(specifier.slice(2));
  }
  return { code: outputText.trim(), requires };
}

export function bundleServiceWorker(): string {
  const modules = new Map<string, string>();
  const pending = [ENTRY];
  while (pending.length) {
    const name = pending.shift()!;
    if (modules.has(name)) continue;
    const { code, requires } = transpile(name);
    modules.set(name, code);
    pending.push(...requires);
  }
  const table = [...modules.keys()]
    .sort()
    .map((name) => `"./${name}": function (exports, require) {\n${modules.get(name)!}\n},`)
    .join("\n");
  return `${HEADER}(() => {
"use strict";
const modules = {
${table}
};
const loaded = {};
function require(name) {
  if (!loaded[name]) {
    loaded[name] = {};
    modules[name](loaded[name], require);
  }
  return loaded[name];
}
require("./${ENTRY}").installServiceWorker(self);
})();
`;
}

